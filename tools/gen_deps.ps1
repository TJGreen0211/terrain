<#
.SYNOPSIS
    Header dependencies for nmake, from cl's /sourceDependencies output.

.DESCRIPTION
    src\Makefile runs this before every build. For each <obj dir>\**\X.c.json
    the last build wrote, it emits one nmake line

        <ObjDir>\<sub>\X.obj: <header> <header> ...

    listing the project headers that X.c included (system and SDK headers are
    left out). Headers that no longer exist are dropped, so deleting a header
    never leaves nmake with a target it cannot make. The first build has no
    JSON yet; everything compiles anyway, so no dependencies are needed.

    -ObjDir must be spelled exactly as the Makefile's $(OBJDIR), because nmake
    matches these target names against $(OBJS) textually.
#>
param(
    [Parameter(Mandatory)] [string]$ObjDir,
    [Parameter(Mandatory)] [string]$Out
)
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path.TrimEnd('\') + '\'

if (-not (Test-Path $ObjDir)) { exit 0 }
$objFull = (Resolve-Path $ObjDir).Path.TrimEnd('\')

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# Generated by tools\gen_deps.ps1 - do not edit.')
foreach ($json in Get-ChildItem -Path $objFull -Recurse -Filter *.c.json) {
    $sub = $json.DirectoryName.Substring($objFull.Length).TrimStart('\')
    # cl lowercases the JSON name; take the .obj's on-disk spelling, which
    # matches $(OBJS). No .obj (failed compile): nothing to depend on yet.
    $want = $json.Name -replace '\.c\.json$', '.obj'
    $objFile = Get-ChildItem -LiteralPath $json.DirectoryName -Filter *.obj |
        Where-Object { $_.Name -ieq $want } | Select-Object -First 1
    if (-not $objFile) { continue }
    $base = $objFile.Name
    $obj = if ($sub) { "$ObjDir\$sub\$base" } else { "$ObjDir\$base" }
    try {
        $data = (Get-Content -LiteralPath $json.FullName -Raw | ConvertFrom-Json).Data
    } catch { continue }   # partial JSON from an interrupted compile
    $headers = @($data.Includes | Where-Object {
            $_.StartsWith($root, [StringComparison]::OrdinalIgnoreCase) -and (Test-Path -LiteralPath $_)
        } | ForEach-Object { if ($_ -match ' ') { "`"$_`"" } else { $_ } } | Sort-Object -Unique)
    if ($headers.Count) { $lines.Add("${obj}: " + ($headers -join ' ')) }
}
Set-Content -LiteralPath $Out -Value $lines -Encoding ASCII
exit 0
